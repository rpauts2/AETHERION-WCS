#!/usr/bin/env python3
"""Audit AETHERION-owned Source 2 particle references.

Stock CS2 resources are excluded because they belong to the game depot.
"""
from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

PARTICLE_REF = re.compile(r"""['"](?P<path>particles/[A-Za-z0-9_./-]+\.vpcf)['"]""", re.IGNORECASE)
CUSTOM_PREFIXES = ("particles/aether_", "particles/aetherion/")
TEXT_SUFFIXES = {".cs", ".json"}


def scan(root: Path):
    references = defaultdict(list)
    for base in (root / "src", root / "configs"):
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if not path.is_file() or path.suffix.lower() not in TEXT_SUFFIXES:
                continue
            try:
                content = path.read_text(encoding="utf-8-sig")
            except (UnicodeDecodeError, OSError):
                continue
            for match in PARTICLE_REF.finditer(content):
                reference = match.group("path").replace("\\", "/")
                if reference.lower().startswith(CUSTOM_PREFIXES):
                    references[reference].append(path.relative_to(root).as_posix())

    missing = []
    for reference in sorted(references, key=str.lower):
        source = root / reference
        compiled = root / (reference + "_c")
        if not source.is_file() and not compiled.is_file():
            missing.append(reference)

    extracted = root / "gb_models" / "extracted"
    counts = {
        "source_vpcf": sum(1 for p in root.rglob("*.vpcf") if p.is_file()),
        "compiled_vpcf": sum(1 for p in root.rglob("*.vpcf_c") if p.is_file()),
        "quarantined_model_files": sum(1 for p in extracted.rglob("*") if p.is_file()) if extracted.exists() else 0,
    }
    return references, missing, counts


def render(references, missing, counts):
    lines = [
        "# AETHERION visual asset reference audit", "",
        "Generated by scripts/audit_asset_references.py.", "",
        "## Inventory", "",
        f"- Source VPCF files in repository: **{counts['source_vpcf']}**",
        f"- Compiled VPCF_C files in repository: **{counts['compiled_vpcf']}**",
        f"- Files under gb_models/extracted (not license-cleared by this audit): **{counts['quarantined_model_files']}**",
        f"- Unique AETHERION-owned particle references: **{len(references)}**",
        f"- Missing AETHERION-owned particle resources: **{len(missing)}**", "",
        "Stock CS2 particle paths are excluded because their resources belong to the game depot.",
        "This report checks file presence only. It does not prove compilation, precache, rendering, or client delivery.", "",
        "## AETHERION-owned particle references", ""
    ]
    if not references:
        lines.append("No AETHERION-owned particle references found.")
    for reference in sorted(references, key=str.lower):
        status = "MISSING" if reference in missing else "present"
        callsites = ", ".join(sorted(set(references[reference])))
        lines.extend((f"- **{status}** {reference}", f"  Referenced from: {callsites}"))
    lines.extend(("", "## Interpretation", "",
        "- Missing custom references need a real Source 2 particle resource or a code/config change to a verified stock effect.",
        "- Assets in gb_models/extracted remain quarantined until provenance and license are recorded per package.",
        "- A successful static audit is not a Workshop Tools compile or an in-game visual test.", ""))
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--fail-on-missing", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    references, missing, counts = scan(root)
    report = render(references, missing, counts)
    if args.output:
        output = args.output if args.output.is_absolute() else root / args.output
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(report, encoding="utf-8")
    print(f"Asset reference audit: {len(references)} custom reference(s), {len(missing)} missing, "
          f"{counts['source_vpcf']} source VPCF, {counts['compiled_vpcf']} compiled VPCF_C")
    for reference in missing:
        print(f"MISSING: {reference}")
    return 1 if args.fail_on_missing and missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
